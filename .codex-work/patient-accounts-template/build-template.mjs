import fs from "node:fs/promises";
import { SpreadsheetFile, Workbook } from "@oai/artifact-tool";

const workbook = Workbook.create();
const entry = workbook.worksheets.add("Patient Accounts");
const instructions = workbook.worksheets.add("Instructions");

entry.showGridLines = false;
entry.freezePanes.freezeRows(1);
entry.getRange("A1:J1").values = [[
  "ID Number",
  "Patient Type",
  "First Name",
  "Middle Name",
  "Last Name",
  "Birthdate",
  "Program or Department",
  "Year Level or Employment Type",
  "Section or Position",
  "Academic Year",
]];
entry.getRange("A1:J1").format = {
  fill: "#23422C",
  font: { bold: true, color: "#FFFFFF" },
  wrapText: true,
  verticalAlignment: "center",
  borders: { preset: "inside", style: "thin", color: "#4E6756" },
};
entry.getRange("A1:J1").format.rowHeight = 34;
entry.getRange("A2:J101").format = {
  fill: "#FFF7D6",
  font: { color: "#17261D" },
  borders: {
    insideHorizontal: { style: "thin", color: "#E5E7EB" },
    bottom: { style: "thin", color: "#CBD5E1" },
  },
};
entry.getRange("A2:A101").format.numberFormat = "@";
entry.getRange("F2:F101").format.numberFormat = "yyyy-mm-dd";
entry.getRange("B2:B101").dataValidation = {
  rule: { type: "list", values: ["student", "faculty", "patient"] },
};
entry.getRange("A:A").format.columnWidth = 16;
entry.getRange("B:B").format.columnWidth = 15;
entry.getRange("C:E").format.columnWidth = 18;
entry.getRange("F:F").format.columnWidth = 14;
entry.getRange("G:J").format.columnWidth = 27;

instructions.showGridLines = false;
instructions.getRange("A1:F1").merge();
instructions.getRange("A1").values = [["CLINiQ Patient Account Import Guide"]];
instructions.getRange("A1:F1").format = {
  fill: "#23422C",
  font: { bold: true, color: "#FFFFFF", size: 16 },
  verticalAlignment: "center",
};
instructions.getRange("A1:F1").format.rowHeight = 32;
instructions.getRange("A3:B10").values = [
  ["Rule", "Description"],
  ["One person per row", "Complete the Patient Accounts worksheet only."],
  ["ID Number", "Required. Keep leading zeroes and hyphens exactly as issued."],
  ["Patient Type", "Required: student, faculty, or patient."],
  ["Names", "First and last name are required. Middle name is optional."],
  ["Birthdate", "Required. Use YYYY-MM-DD."],
  ["Student details", "Use Program, Year Level, Section, and Academic Year."],
  ["Faculty details", "Use Department, Employment Type, and Position."],
];
instructions.getRange("A3:B3").format = {
  fill: "#E8F6EC",
  font: { bold: true, color: "#23422C" },
  borders: { preset: "outside", style: "thin", color: "#C7DCCD" },
};
instructions.getRange("A4:B10").format = {
  wrapText: true,
  verticalAlignment: "top",
  borders: { insideHorizontal: { style: "thin", color: "#E5E7EB" } },
};
instructions.getRange("A:A").format.columnWidth = 24;
instructions.getRange("B:B").format.columnWidth = 68;
instructions.getRange("A12:F13").merge();
instructions.getRange("A12").values = [[
  "Temporary passwords are generated by CLINiQ after import using the last three ID digits repeated twice. Do not add passwords to this workbook.",
]];
instructions.getRange("A12:F13").format = {
  fill: "#FFF7D6",
  font: { color: "#7C5E10" },
  wrapText: true,
  verticalAlignment: "center",
  borders: { preset: "outside", style: "thin", color: "#E8D99A" },
};

await fs.mkdir("C:/xampp/htdocs/CLINiQ/outputs/patient-accounts", { recursive: true });
await fs.mkdir("C:/xampp/htdocs/CLINiQ/public/assets/templates", { recursive: true });

const preview = await workbook.render({
  sheetName: "Patient Accounts",
  range: "A1:J8",
  scale: 1.5,
  format: "png",
});
await fs.writeFile(
  "C:/xampp/htdocs/CLINiQ/outputs/patient-accounts/template-preview.png",
  new Uint8Array(await preview.arrayBuffer()),
);
const instructionsPreview = await workbook.render({
  sheetName: "Instructions",
  range: "A1:F14",
  scale: 1.5,
  format: "png",
});
await fs.writeFile(
  "C:/xampp/htdocs/CLINiQ/outputs/patient-accounts/instructions-preview.png",
  new Uint8Array(await instructionsPreview.arrayBuffer()),
);

const inspect = await workbook.inspect({
  kind: "table",
  range: "Patient Accounts!A1:J5",
  include: "values,formulas",
  tableMaxRows: 5,
  tableMaxCols: 10,
});
console.log(inspect.ndjson);
const errors = await workbook.inspect({
  kind: "match",
  searchTerm: "#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A",
  options: { useRegex: true, maxResults: 100 },
  summary: "final formula error scan",
});
console.log(errors.ndjson);

const output = await SpreadsheetFile.exportXlsx(workbook);
await output.save("C:/xampp/htdocs/CLINiQ/outputs/patient-accounts/cliniq-patient-account-import.xlsx");
await output.save("C:/xampp/htdocs/CLINiQ/public/assets/templates/cliniq-patient-account-import.xlsx");
